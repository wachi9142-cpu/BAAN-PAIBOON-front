function seeded(seed: number) {
  let s = seed | 0
  return () => {
    s = (s + 0x6d2b79f5) | 0
    let t = Math.imul(s ^ (s >>> 15), 1 | s)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** คำทำนายของ (สัปดาห์, กระบอก, เลข) — คงที่ทั้งสัปดาห์ เปลี่ยนชุดเมื่อขึ้นสัปดาห์ใหม่ */
export function fortuneOf(week: number, cup: 0 | 1 | 2, no: number): Fortune {
  const r = seeded(week * 7919 + cup * 104729 + no * 31)
  const roll = r()
  const level: FortuneLevel = roll < 0.38 ? 'lucky' : roll < 0.8 ? 'normal' : 'careful'
  const aspects = CUPS[cup].aspects
  const aspect = aspects[Math.floor(r() * aspects.length)]
  const img = IMAGES[Math.floor(r() * IMAGES.length)]
  const say = SAY[aspect][level]
  const text = `${img} ${say[Math.floor(r() * say.length)]}`
  const advice = ADVICE[level][Math.floor(r() * ADVICE[level].length)]
  const f: Fortune = { week, cup, no, level, aspect, text, advice }
  // บางใบมีโบนัสเล็ก ๆ หรือเบาะแส
  const extra = r()
  if (level === 'lucky' && extra < 0.35) f.bonus = { coins: 9 + Math.floor(r() * 3) * 10 }
  else if (level !== 'careful' && extra < 0.55) f.bonus = { fun: 5 }
  if (aspect === 'luck' && level !== 'careful' && r() < 0.5) f.clue = CLUES[Math.floor(r() * CLUES.length)]
  return f
}
